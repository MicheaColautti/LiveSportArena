// Regenerate after updating site/maps-3d: node backend/build-ski-profiles.mjs
import fs from 'node:fs';
import vm from 'node:vm';
import { skiMaps } from '../site/assets/maps-3d.js';

const profiles = {};
for (const { id } of skiMaps) {
  const page = fs.readFileSync(new URL('../site/maps-3d/' + id + '.html', import.meta.url), 'utf8');
  const course = JSON.parse(page.match(/window\.LSA_COURSE=(.*?);<\/script>/s)[1]);
  const engine = page.match(/<script>(\/\* LiveSportArena 3D · engine\.js.*?\}\)\(window\.LSA = window\.LSA \|\| \{\}\);)/s)[1];
  const context = { window: {} };
  vm.runInNewContext(engine, context);
  const world = new context.window.LSA.World(course.model);
  const heights = Array.from({length:81}, (_, i) => world.point(i/80)[1]);
  const upper = Math.max(...heights), range = upper - Math.min(...heights);
  if (!(range > 0)) throw Error('Profilo non valido: ' + id);
  const marks = course.poi.filter(p => p.s > .08 && p.s < .92);
  const chosen = [];
  for (const target of [.30,.70]) {
    const best = marks.filter(p => chosen.every(q => Math.abs(p.s-q.s) > .20))
      .sort((a,b) => Math.abs(a.s-target)-Math.abs(b.s-target))[0];
    if (best) chosen.push(best);
  }
  profiles[id] = { metrics:course.metrics, line:heights.map(h => Math.round(100*(upper-h)/range)),
    marks:chosen.sort((a,b) => a.s-b.s).map(p => [Math.round(80*p.s),p.name]) };
}
fs.writeFileSync(new URL('../site/assets/ski-profiles.js', import.meta.url),
  '// Generated by backend/build-ski-profiles.mjs\nexport const skiProfiles = {\n' +
  Object.entries(profiles).map(([id,p])=>'  '+JSON.stringify(id)+': '+JSON.stringify(p)).join(',\n')+'\n};\n');
